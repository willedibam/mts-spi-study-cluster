"""Write `spis.yaml` (stages 1-2) or, with --stage3, `spis_stage3.yaml`: the p90 configurations scored."""
from __future__ import annotations

import importlib
from pathlib import Path

import pyspi
import yaml

HERE = Path(__file__).resolve().parent
P90 = Path(pyspi.__file__).parent / 'configs' / 'benchmarked_p90.yaml'
B, L, H = 'fmin-0_fmax-0-5', 'fmin-0_fmax-0-25', 'fmin-0-25_fmax-0-5'
mt = lambda f, b: f'{f}_multitaper_mean_fs-1_{b}'
WANTED = {
    # strength references and form
    'cov_EmpiricalCovariance', 'cov-sq_EmpiricalCovariance', 'spearmanr', 'dcorr',
    'mi_gaussian', 'mi_kraskov_NN-4', 'mi_kraskov_NN-4_DCE-AUTO', 'mi_kernel_W-0.25',
    'tlmi_gaussian', 'tlmi_kraskov_NN-4_DCE-AUTO',
    'gc_gaussian_k-1_kt-1_l-1_lt-1', 'te_kraskov_NN-4_DCE-AUTO_k-1_kt-1_l-1_lt-1',
    # mediation
    'cov-sq_LedoitWolf', 'prec-sq_LedoitWolf', 'prec-sq_EmpiricalCovariance',
    # lag and band
    *[mt('cohmag', b) for b in (B, L, H)], *[mt('icoh', b) for b in (B, L, H)],
    mt('plv', B), mt('wpli', B), mt('ppc', B), mt('dswpli', B), mt('ppc', L), mt('ppc', H),
    'pec', 'pec_orth',
    'sgc_nonparametric_mean_fs-1_fmin-1e-05_fmax-0-5', 'sgc_nonparametric_mean_fs-1_fmin-1e-05_fmax-0-25',
    'sgc_nonparametric_mean_fs-1_fmin-0-25_fmax-0-5',
    # warp
    'pdist_euclidean', 'dtw_constraint-sakoe-chiba_radius-auto', 'dtw',
}
# Stage 3 (README, "Stage 3"): every constituent of the extended axes and levels under test, exactly as the
# cohort readout defines them, plus the core's constituents (cross-talk) and the top-quartile ranking.
STAGE3_AXES = ('timing_fixed_lag', 'timing_best_shift', 'spectral_peak', 'form_monotone', 'tail')


def stage3_wanted():
    from mtsspi.character_axes import AXES, BAND_RANK, CORE, LEVELS
    w = {s for a in AXES if a.name in STAGE3_AXES for p in a.pairs for s in p}
    w |= {s for k, (a, b, _) in LEVELS.items() if k in STAGE3_AXES for s in (a, b)}
    w |= {s for _, _, a, b in CORE.values() for s in (a, b)}
    return w | {BAND_RANK}


WANTED3 = stage3_wanted()


def identifier(module, cls, cfg):
    obj = getattr(importlib.import_module('pyspi' + module), cls)(**{k: v for k, v in (cfg or {}).items() if k != 'labels'})
    return obj.identifier


def main():
    import sys
    stage3 = '--stage3' in sys.argv[1:]
    wanted, target = (WANTED3, 'spis_stage3.yaml') if stage3 else (WANTED, 'spis.yaml')
    full = yaml.safe_load(P90.read_text())
    out, found = {}, set()
    for module, classes in full.items():
        for cls, spec in classes.items():
            keep = []
            for cfg in spec.get('configs') or [None]:
                try:
                    name = identifier(module, cls, cfg)
                except Exception as e:  # noqa: BLE001 - report and continue
                    print('skip', module, cls, cfg, type(e).__name__, e); continue
                if name in wanted:
                    keep.append(cfg); found.add(name)
            if keep:
                out.setdefault(module, {})[cls] = {**{k: v for k, v in spec.items() if k != 'configs'},
                                                   'configs': None if keep == [None] else keep}
    missing = wanted - found
    if missing:
        raise SystemExit(f'not in p90: {sorted(missing)}')
    (HERE / target).write_text('# Generated by build_subset.py from pyspi benchmarked_p90.yaml.\n'
                                    + yaml.safe_dump(out, sort_keys=False))
    print(f'{len(found)} statistics written')


if __name__ == '__main__':
    main()
